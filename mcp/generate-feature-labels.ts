/** Internal build/check helper: control labels for capability_catalog feature search (mcp/feature-index.mjs).
 * Regenerate mcp/feature-labels.json after changing either control registry:
 *   node --import tsx mcp/generate-feature-labels.ts --write */
import fs from "node:fs";
import { pathToFileURL } from "node:url";
import { EFFECT_CONTROLS } from "../src/lib/timeline/effect-controls";
import { PROPOSAL_TUNABLE_FIELDS } from "../src/lib/agent/proposal-controls";

/** Labels per field, from the effect-control and proposal-tunable registries. */
export function deriveControlLabels(): Record<string, string[]> {
  const labels: Record<string, string[]> = {};
  const add = (field: string, label: string | undefined) => { if (label && !(labels[field] ??= []).includes(label)) labels[field].push(label); };
  for (const control of EFFECT_CONTROLS) { add(control.prop, control.label); add(control.prop, control.proposal?.label); }
  for (const [field, spec] of Object.entries(PROPOSAL_TUNABLE_FIELDS)) add(field, spec.label);
  return Object.fromEntries(Object.entries(labels).sort(([a], [b]) => a.localeCompare(b)));
}

if (process.argv.includes("--write") && import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const labels = deriveControlLabels();
  fs.writeFileSync(new URL("./feature-labels.json", import.meta.url), JSON.stringify({ about: "Generated by `node --import tsx mcp/generate-feature-labels.ts --write` from EFFECT_CONTROLS and PROPOSAL_TUNABLE_FIELDS. Do not edit by hand.", labels }, null, 2) + "\n");
  console.log(`Wrote ${Object.keys(labels).length} control labels.`);
}
