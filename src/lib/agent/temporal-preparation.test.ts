import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { runBackgroundCommand } from "../local-store/background-worker";
import { readPreparation, writePreparation } from "../local-store/media-preparation";
import { mediaReadiness } from "./media-readiness";
import { executePreparation, getPreparationJob } from "./preparation-jobs";

test("temporal jobs deduplicate, authenticate artifacts, preserve timeline and recover explicitly", async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "temporal-job-test-")), previous = { ...process.env };
  process.env.TIMELINE_PROJECTS_DIR = root;
  process.env.AGENT_PREPARATION_AUTOSTART = "0";
  process.env.MEDIA_PREPARATION_AUTOSTART = "0";
  try {
    const project = "fixture", dir = path.join(root, project), media = path.join(dir, "media");
    fs.mkdirSync(media, { recursive: true });
    const timeline = JSON.stringify({ schema_version: 1, elements: [], transitions: [] });
    fs.writeFileSync(path.join(dir, "timeline.json"), timeline);
    fs.writeFileSync(path.join(dir, "metadata.json"), JSON.stringify({ frame_rate: 24 }));
    const source = path.join(media, "take.mp4");
    await runBackgroundCommand("ffmpeg", ["-v", "error", "-f", "lavfi", "-i", "testsrc2=size=64x64:rate=24:duration=0.375", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-color_primaries", "bt709", "-color_trc", "bt709", "-colorspace", "bt709", source]);
    const args = { source: "take.mp4", temporal_average: { sample_frames: 5 } };
    await assert.rejects(mediaReadiness(project, { ...args, action: "status" }), /job_id/);
    await assert.rejects(mediaReadiness(project, { ...args, source: "../take.mp4", action: "prepare" }), /inside/);
    const queued = await mediaReadiness(project, { ...args, action: "prepare" });
    assert.equal(queued.state, "queued");
    const id = String(queued.job_id);
    const duplicate = await mediaReadiness(project, { ...args, source: "media/take.mp4", action: "prepare" });
    assert.equal(duplicate.job_id, id); assert.equal(duplicate.reused, true);
    await assert.rejects(mediaReadiness(project, { ...args, temporal_average: { sample_frames: 3 }, job_id: id, action: "status" }), /does not belong/);
    await executePreparation(project, id);
    const completed = await mediaReadiness(project, { ...args, job_id: id, action: "status" });
    assert.equal(completed.preparation_state, "completed");
    assert.equal(completed.state, "preparing", "technical proxy still pending, never falsely ready");
    const receipt = await getPreparationJob(project, id);
    assert.equal(receipt.result?.frame_count, 9);
    assert.equal(receipt.result?.original_source_url, "/api/projects/fixture/media/take.mp4");
    assert.equal(fs.readFileSync(path.join(dir, "timeline.json"), "utf8"), timeline);
    const derivative = String(receipt.result?.output_relative_path);
    const pendingPreview = readPreparation(project, derivative)!;
    writePreparation(project, { ...pendingPreview, state: "failed", error: "Interrupted preview worker" });
    const failedPreview = await mediaReadiness(project, { ...args, job_id: id, action: "status" });
    assert.equal(failedPreview.state, "failed");
    const previewRetry = await mediaReadiness(project, { ...args, job_id: id, action: "retry" });
    assert.equal(previewRetry.job_id, id, "completed averaging is reused");
    assert.equal(previewRetry.preparation_state, "completed");
    assert.equal(previewRetry.state, "preparing", "explicit retry restarts the failed derivative preview");
    assert.equal(readPreparation(project, derivative)?.state, "preparing");
    assert.equal(readPreparation(project, derivative)?.error, undefined);
    const output = path.join(media, derivative);
    fs.appendFileSync(output, "corruption");
    await assert.rejects(mediaReadiness(project, { ...args, job_id: id, action: "status" }), /evidence changed/);
    fs.appendFileSync(source, "changed source");
    await assert.rejects(mediaReadiness(project, { ...args, job_id: id, action: "status" }), /Source bytes changed/);
    const retried = await mediaReadiness(project, { ...args, action: "retry" });
    assert.notEqual(retried.job_id, id, "changed source gets a separate version, old job is retained");
    const otherMedia=path.join(root,"other","media"),outside=path.join(root,"outside");
    fs.mkdirSync(otherMedia,{recursive:true});fs.mkdirSync(outside);
    fs.copyFileSync(source,path.join(otherMedia,"take.mp4"));
    fs.symlinkSync(outside,path.join(otherMedia,"temporal-averages"),"dir");
    const unsafe=await mediaReadiness("other",{...args,action:"prepare"});
    await executePreparation("other",String(unsafe.job_id));
    const refused=await getPreparationJob("other",String(unsafe.job_id));
    assert.equal(refused.state,"failed");assert.match(refused.error!,/inside project media/);
    assert.deepEqual(fs.readdirSync(outside),[],"unsafe output alias creates no files outside project media");
    assert.equal(fs.readFileSync(path.join(dir, "timeline.json"), "utf8"), timeline);
  } finally { process.env = previous; fs.rmSync(root, { recursive: true, force: true }); }
});
