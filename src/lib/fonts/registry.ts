export const FONT_CATEGORIES = [
  "Sans Serif",
  "Serif",
  "Display",
  "Handwriting",
  "Monospace",
] as const;

export type FontCategory = (typeof FONT_CATEGORIES)[number];

export type SharedFontDefinition = {
  id: string;
  label: string;
  family: string;
  category: FontCategory;
  cssFontFamily: string;
  remotionFontFamily: string;
  aliases: readonly string[];
};

function defineFont(input: Omit<SharedFontDefinition, "aliases"> & { aliases?: readonly string[] }): SharedFontDefinition {
  return {
    ...input,
    aliases: Array.from(new Set([input.family, input.cssFontFamily, ...(input.aliases ?? [])])),
  };
}

