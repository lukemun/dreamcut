export type SharedFontId = (typeof SHARED_FONT_LIBRARY)[number]["id"];

export const SHARED_FONT_BY_ID: Record<SharedFontId, SharedFontDefinition> = Object.fromEntries(
  SHARED_FONT_LIBRARY.map((font) => [font.id, font]),
) as Record<SharedFontId, SharedFontDefinition>;

export const SHARED_FONTS_BY_CATEGORY = FONT_CATEGORIES.map((category) => ({
  category,
  fonts: SHARED_FONT_LIBRARY.filter((font) => font.category === category),
})).filter((group) => group.fonts.length > 0);

export function getSharedFont(id: SharedFontId) {
  return SHARED_FONT_BY_ID[id];
}

export function findSharedFontByFamily(fontFamily: string | null | undefined) {
  if (!fontFamily) return null;
  const normalized = fontFamily.trim().toLowerCase();
  return SHARED_FONT_LIBRARY.find((font) =>
    font.aliases.some((alias) => alias.trim().toLowerCase() === normalized)
  ) ?? null;
}

/** CSS custom properties named by cssFontFamily, mapped to the quoted family they stand for. */
export function sharedFontCssVariables(): Record<string, string> {
  return Object.fromEntries(SHARED_FONT_LIBRARY.flatMap((font) => {
    const variable = font.cssFontFamily.match(/^var\((--font-[a-z0-9-]+)\)/)?.[1];
    return variable ? [[variable, `'${font.family}'`]] : [];
  }));
}
