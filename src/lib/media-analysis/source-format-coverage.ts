/** The resolved entry for one stage, format and platform; Windows falls back to unverified. */
export function coverageFor(stage: CoverageStage, format: SourceFormatClassId, platform: CoveragePlatform): CoverageEntry | null {
  const entries = stage.formats[format];
  if (!entries) return null;
  return entries[platform] ?? (platform === "macos" ? null : WINDOWS_UNVERIFIED);
}

