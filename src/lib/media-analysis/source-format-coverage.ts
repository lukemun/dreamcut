/** The primary class of a probed video. VFR and rotation are separate traits a clip can also carry. */
export function classifySourceFormat(probe: SourceFormatProbe): SourceFormatClassId {
  const transfer = probe.color_transfer?.toLowerCase() ?? "";
  if (transfer === "arib-std-b67") return "hlg-hevc-10bit";
  if (transfer === "smpte2084") return probe.hdr10_plus ? "pq-hdr10plus" : "pq-hevc-10bit";
  const pixelFormat = probe.pixel_format?.toLowerCase() ?? "";
  if (probe.color_range === "pc" || pixelFormat.startsWith("yuvj")) return "sdr-full-range";
  const primaries = probe.color_primaries?.toLowerCase() ?? "";
  if (primaries === "smpte170m" || primaries === "bt470bg" || (probe.height ?? 0) > 0 && (probe.height ?? 0) <= 576) return "sdr-601-sd";
  return probe.codec_name?.toLowerCase() === "hevc" ? "sdr-hevc-709" : "sdr-h264-709";
}

export function sourceFormatTraits(probe: SourceFormatProbe): SourceFormatClassId[] {
  const traits: SourceFormatClassId[] = [classifySourceFormat(probe)];
  if (probe.variable_frame_rate) traits.push("variable-frame-rate");
  if (Math.abs(probe.rotation_degrees ?? 0) % 360 !== 0) traits.push("rotation-metadata");
  return traits;
}

export type CoverageEntry = {
  status: CoverageStatus;
  note?: string;
  /** Repository paths of tests or scripts, or `pnpm <script>`. Required for supported/fallback. */
  evidence?: string[];
  /** A recorded windows-compatibility receipt id. Required for a supported Windows entry. */
  windows_receipt?: string;
};

type PlatformEntries = Partial<Record<CoveragePlatform, CoverageEntry>>;

export type CoverageStage = {
  id: string;
  label: string;
  /** Code that owns the stage. */
  owners: string[];
  /** Preparation recipe ids this stage produces; every exported recipe must be listed by some stage. */
  recipes: string[];
  /** Status for a format on platforms it does not name. Windows defaults to unverified. */
  formats: Record<SourceFormatClassId, PlatformEntries>;
};

